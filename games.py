def verdict(pct):
    if pct >= 70:
        return "🏆 คุณเหมาะกับคณะวิศวกรรมศาสตร์มาก! พร้อมทั้งตรรกะและการคำนวณพื้นฐาน"
    if pct >= 50:
        return "⚖️ คุณมีพื้นฐานพอจะเรียนต่อวิศวะได้ แต่ควรฟิตสูตรและการคำนวณเพิ่ม"
    return "📚 ตอนนี้ยังไม่ค่อยเหมาะ แต่ปูพื้นฐานคณิต-ฟิสิกส์ ม.ปลาย เพิ่มได้แน่นอน"


def solo():
    me = Player("คุณ")
    while True:
        show_board([me])
        ended, _ = take_turn(me)
        if ended:
            break
    pct = round(me.correct / me.total * 100) if me.total else 0
    print("\n===== จบเกม =====")
    print(f"ตอบถูก {me.correct} จาก {me.total} ข้อ = {pct}%")
    print(verdict(pct))


