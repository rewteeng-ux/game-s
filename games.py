# ====================== ผู้เล่น ======================
class Player:
    def __init__(self, name):
        self.name = name
        self.pos = 1
        self.correct = 0
        self.total = 0
        self.solved = [set(), set()]  # ข้อที่ตอบถูกแล้ว แยกตามโซน


def read(prompt):
    try:
        return input(prompt)
    except (EOFError, KeyboardInterrupt):
        print("\nออกจากเกม")
        sys.exit(0)


# ====================== กระดาน ======================
def square_at(row, col):
    """row 0 = แถวล่างสุด (ช่อง 1-10)"""
    return row * 10 + col + 1 if row % 2 == 0 else row * 10 + (10 - col)


def show_board(players):
    marks = {}
    for tag, p in zip("AB", players):
        marks.setdefault(p.pos, "")
        marks[p.pos] += tag
    print()
    for row in range(9, -1, -1):
        cells = []
        for col in range(10):
            n = square_at(row, col)
            if n in marks:
                tag = marks[n] if len(marks[n]) == 1 else "*"
                cells.append(f"[{tag}{n:>3}]")
            elif n in LADDERS:
                cells.append(f" {n:>3}^ ")
            elif n in SNAKES:
                cells.append(f" {n:>3}v ")
            else:
                cells.append(f" {n:>3}  ")
        print("".join(cells))
    print("\n  ^ = โคนบันได   v = หัวงู   [A]/[B] = ผู้เล่น   * = อยู่ช่องเดียวกัน")
    for tag, p in zip("AB", players):
        print(f"  {tag}: {p.name:<12} ช่อง {p.pos:>3}   ตอบถูก {p.correct}/{p.total}")
    print()


# ====================== คำถาม ======================
def ask(pos, me):
    """ถามคำถามของช่อง pos คืน True ถ้าตอบถูก"""
    zone = 0 if pos <= 50 else 1
    pool = [i for i in range(len(ZONES[zone])) if i not in me.solved[zone]]
    if not pool:  # เคยตอบถูกครบทั้งโซนแล้ว
        print("  (ตอบคำถามของโซนนี้ถูกครบแล้ว ผ่านได้เลย)")
        return True
    idx = random.choice(pool)
    text, options, answer = ZONES[zone][idx]
    print("-" * 60)
    print(f"ช่อง {pos} · {'โซนพื้นฐาน' if zone == 0 else 'โซนขั้นสูง'}")
    print(text)
    for i, o in enumerate(options, 1):
        print(f"  {i}) {o}")
    while True:
        s = read("คำตอบของคุณ (1-3): ").strip()
        if s in ("1", "2", "3"):
            choice = int(s) - 1
            break
        print("  พิมพ์ 1, 2 หรือ 3 เท่านั้นนะ")
    me.total += 1
    ok = choice == answer
    if ok:
        me.correct += 1
        me.solved[zone].add(idx)
        print("  ✅ ถูกต้อง!")
    else:
        print(f"  ❌ ยังไม่ถูก คำตอบที่ถูกคือ: {answer + 1}) {options[answer]}")
    print("-" * 60)
    return ok


def land(pos, me, log, chain=False):
    """จัดการเมื่อลงช่อง pos คืน (จบเกมไหม, ตำแหน่งสุดท้าย)"""

    def say(t):
        print(t)
        log.append(t)

    if pos == 100:
        ask(pos, me)
        return True, 100
    if not chain and pos in LADDERS:
        if ask(pos, me):
            top = LADDERS[pos]
            say(f"🪜 ตอบถูก! ไต่บันไดขึ้นไปช่อง {top} และมีคำถามพิเศษ 1 ข้อ")
            me.pos = top
            return land(top, me, log, chain=True)
        say("ตอบไม่ถูก ยังไม่ได้ไต่บันได อยู่ช่องเดิม")
        return False, pos
    if not chain and pos in SNAKES:
        if ask(pos, me):
            say("🐍 ตอบถูก! รอดจากงูตัวนี้ ยืนช่องเดิม")
            return False, pos
        tail = SNAKES[pos]
        say(f"🐍 ตอบไม่ถูก ตกลงไปหางงูที่ช่อง {tail}")
        return False, tail
    ask(pos, me)
    return False, pos


def take_turn(me):
    """เล่น 1 ตา คืน (จบเกมไหม, log ที่จะส่งให้อีกฝั่งดู)"""
    log = []
    read(f"ถึงตา {me.name} — กด Enter เพื่อทอยลูกเต๋า...")
    roll = random.randint(1, 6)
    target = me.pos + roll
    if target > 100:
        t = f"🎲 {me.name} ทอยได้ {roll} เกินช่อง 100 ต้องทอยให้พอดี ข้ามตา"
        print(t)
        return False, [t]
    t = f"🎲 {me.name} ทอยได้ {roll} เดินจากช่อง {me.pos} ไปช่อง {target}"
    print(t)
    log.append(t)
    me.pos = target
    ended, final_pos = land(target, me, log)
    me.pos = final_pos
    return ended, log


