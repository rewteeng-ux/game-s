class Link:
    """ส่ง/รับข้อความ JSON ทีละบรรทัดผ่าน TCP"""

    def __init__(self, sock):
        self.sock = sock
        self.f = sock.makefile("rw", encoding="utf-8", newline="\n")

    def send(self, obj):
        self.f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        self.f.flush()

    def recv(self):
        line = self.f.readline()
        return json.loads(line) if line else None


def online(role, host_ip, port):
    name = read("ชื่อของคุณ: ").strip() or ("ผู้เล่น 1" if role == "host" else "ผู้เล่น 2")

    if role == "host":
        srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        srv.bind(("0.0.0.0", port))
        srv.listen(1)
        print(f"รอเพื่อนเข้าห้องที่พอร์ต {port} ... (ให้เพื่อนรัน: python snake_ladder.py join <IP ของคุณ> {port})")
        sock, addr = srv.accept()
        print(f"เพื่อนเข้าห้องแล้ว ({addr[0]})")
        idx = 0
    else:
        sock = socket.create_connection((host_ip, port), timeout=10)
        sock.settimeout(None)
        idx = 1

    link = Link(sock)
    link.send({"name": name})
    hello = link.recv()
    if hello is None:
        print("การเชื่อมต่อถูกตัดก่อนเริ่มเกม")
        return
    players = [None, None]
    players[idx] = Player(name)
    players[1 - idx] = Player(hello["name"])
    me, opp = players[idx], players[1 - idx]

    print(f"\nเริ่มเกม! {players[0].name} (A) vs {players[1].name} (B) — ใครถึงช่อง 100 ก่อนชนะ")
    turn = 0  # โฮสต์เริ่มก่อน
    while True:
        show_board(players)
        if turn == idx:
            ended, log = take_turn(me)
            link.send({"pos": me.pos, "correct": me.correct, "total": me.total,
                       "ended": ended, "log": log})
            if ended:
                show_board(players)
                print(f"🏆 คุณถึงช่อง 100 ก่อน — {me.name} ชนะ!")
                return
        else:
            print(f"รอ {opp.name} เล่นตา... ")
            msg = link.recv()
            if msg is None:
                print("เพื่อนหลุดจากเกม")
                return
            for t in msg["log"]:
                print(t)
            opp.pos, opp.correct, opp.total = msg["pos"], msg["correct"], msg["total"]
            if msg["ended"]:
                show_board(players)
                print(f"{opp.name} ถึงช่อง 100 ก่อน — คุณแพ้ในรอบนี้")
                return
        turn = 1 - turn


# ====================== main ======================
def main():
    args = sys.argv[1:]
    if not args or args[0] == "solo":
        solo()
    elif args[0] == "host":
        online("host", None, int(args[1]) if len(args) > 1 else 5000)
    elif args[0] == "join" and len(args) >= 2:
        online("join", args[1], int(args[2]) if len(args) > 2 else 5000)
    else:
        print(__doc__)


if __name__ == "__main__":
    main()